// Writes wrangler.local.jsonc: the real config minus bindings that only work against a live
// Cloudflare account (Workers AI), so `npm run dev` works offline with no sign-in.
import { readFileSync, writeFileSync } from 'node:fs';
const src = readFileSync('wrangler.jsonc', 'utf8');
const out = src.replace(/^\s*"ai":\s*\{[^}]*\},?\s*\n/m, '');
writeFileSync('wrangler.local.jsonc', '// Generated by scripts/local-config.mjs. Do not edit.\n' + out);
